export function anchorsFor(country: string, nation?: UkNation): readonly Anchor[] {
  if (country === "GBR") {
    const list = nation ? UK_ANCHORS.filter((a) => a.nation === nation) : UK_ANCHORS;
    if (list.length === 0) throw new Error(`no UK anchors for ${nation ?? "GBR"}`);
    return list;
  }
  const list = INTL_ANCHORS[country];
  if (!list || list.length === 0) throw new Error(`no anchors for ${country}`);
  return list;
}
